// gencodes 从 API 词典生成消息键常量；独立于 i18n 包，生成文件缺失时也能运行。
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

func main() {
	dir := flag.String("dir", ".", "directory containing messages.json and codes.go")
	check := flag.Bool("check", false, "check generated output without writing it")
	flag.Parse()
	if err := generateFile(*dir, *check); err != nil {
		fmt.Fprintln(os.Stderr, "gencodes:", err)
		os.Exit(1)
	}
}

func generateFile(dir string, check bool) error {
	source, err := os.ReadFile(filepath.Join(dir, "messages.json"))
	if err != nil {
		return err
	}
	generated, err := renderCodes(source)
	if err != nil {
		return err
	}
	output := filepath.Join(dir, "codes.go")
	if check {
		current, err := os.ReadFile(output)
		if err != nil || !bytes.Equal(current, generated) {
			return fmt.Errorf("%s is missing or stale; run go generate ./internal/i18n", output)
		}
		return nil
	}
	return os.WriteFile(output, generated, 0644)
}

func renderCodes(source []byte) ([]byte, error) {
	var catalog map[string]map[string]string
	if err := json.Unmarshal(source, &catalog); err != nil {
		return nil, err
	}
	english := catalog["en"]
	if len(english) == 0 {
		return nil, fmt.Errorf("English catalog must not be empty")
	}
	for locale, messages := range catalog {
		if len(messages) != len(english) {
			return nil, fmt.Errorf("%s catalog keys differ from English", locale)
		}
		for key := range english {
			if _, ok := messages[key]; !ok {
				return nil, fmt.Errorf("%s catalog keys differ from English: missing %s", locale, key)
			}
		}
	}
	keys := make([]string, 0, len(english))
	for key := range english {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	keyPattern := regexp.MustCompile(`^api\.[a-z][a-z0-9]*(_[a-z][a-z0-9]*)*$`)
	names := map[string]string{}
	var output bytes.Buffer
	output.WriteString("// Code generated by go generate ./internal/i18n; DO NOT EDIT.\n// Source: messages.json\n\npackage i18n\n\nconst (\n")
	for _, key := range keys {
		if !keyPattern.MatchString(key) {
			return nil, fmt.Errorf("invalid message key %q", key)
		}
		name := constantName(key)
		if previous, exists := names[name]; exists {
			return nil, fmt.Errorf("message keys %q and %q produce the same constant %s", previous, key, name)
		}
		names[name] = key
		fmt.Fprintf(&output, "\t%s = %q\n", name, key)
	}
	output.WriteString(")\n")
	return format.Source(output.Bytes())
}

func constantName(key string) string {
	initialisms := map[string]string{
		"csrf": "CSRF", "http": "HTTP", "https": "HTTPS", "ip": "IP",
		"json": "JSON", "smtp": "SMTP", "sse": "SSE", "udid": "UDID",
		"url": "URL", "usb": "USB", "wecom": "WeCom",
	}
	var name strings.Builder
	for _, word := range strings.Split(strings.TrimPrefix(key, "api."), "_") {
		if initialism, ok := initialisms[word]; ok {
			name.WriteString(initialism)
		} else {
			name.WriteString(strings.ToUpper(word[:1]) + word[1:])
		}
	}
	return name.String()
}
